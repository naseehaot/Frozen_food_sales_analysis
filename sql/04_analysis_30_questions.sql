-- 25. Calculate gross profit for each product.
SELECT
    p.product_name,
    SUM(
        (oi.quantity * oi.unit_price)
        - (oi.quantity * pc.cost_per_unit)
    ) AS gross_profit
FROM Order_Items oi
JOIN Products p
    ON oi.product_id = p.product_id
JOIN Production_Costs pc
    ON oi.product_id = pc.product_id
GROUP BY p.product_name
ORDER BY gross_profit DESC;

-- 26. Which product generated the highest gross profit?
SELECT
    p.product_name,
    SUM(
        (oi.quantity * oi.unit_price)
        - (oi.quantity * pc.cost_per_unit)
    ) AS gross_profit
FROM Order_Items oi
JOIN Products p
    ON oi.product_id = p.product_id
JOIN Production_Costs pc
    ON oi.product_id = pc.product_id
GROUP BY p.product_name
ORDER BY gross_profit DESC
LIMIT 1;

-- 27. Calculate profit margin for each product.
SELECT
    p.product_name,
    (
        SUM(
            (oi.quantity * oi.unit_price)
            - (oi.quantity * pc.cost_per_unit)
        )
        / SUM(oi.quantity * oi.unit_price)
    ) * 100 AS profit_margin
FROM Order_Items oi
JOIN Products p
    ON oi.product_id = p.product_id
JOIN Production_Costs pc
    ON oi.product_id = pc.product_id
GROUP BY p.product_name
ORDER BY profit_margin DESC;

-- 28. Which category has the highest profit margin?
SELECT
    c.category_name,
    (
        SUM(
            (oi.quantity * oi.unit_price)
            - (oi.quantity * pc.cost_per_unit)
        )
        / SUM(oi.quantity * oi.unit_price)
    ) * 100 AS profit_margin
FROM Order_Items oi
JOIN Products p
    ON oi.product_id = p.product_id
JOIN Categories c
    ON p.category_id = c.category_id
JOIN Production_Costs pc
    ON oi.product_id = pc.product_id
GROUP BY c.category_name
ORDER BY profit_margin DESC
LIMIT 1;

-- 29. What are the total expenses by expense type?
SELECT
    expense_type,
    SUM(amount) AS total_expense
FROM Expenses
GROUP BY expense_type
ORDER BY total_expense DESC;

-- 30. What is the net profit of the business?
SELECT
    revenue.total_revenue
    - revenue.total_production_cost
    - expenses.total_expenses AS net_profit
FROM
(
    SELECT
        SUM(oi.quantity * oi.unit_price) AS total_revenue,
        SUM(oi.quantity * pc.cost_per_unit) AS total_production_cost
    FROM Order_Items oi
    JOIN Production_Costs pc
        ON oi.product_id = pc.product_id
) revenue
CROSS JOIN
(
    SELECT
        SUM(amount) AS total_expenses
    FROM Expenses
) expenses;
